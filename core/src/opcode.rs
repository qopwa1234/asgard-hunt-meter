pub fn name(dir: crate::frame::Dir, op: u8) -> &'static str {
    match dir {
        crate::frame::Dir::S2C => s2c_name(op),
        crate::frame::Dir::C2S => c2s_name(op),
        crate::frame::Dir::Unknown => {
            let s = s2c_name(op);
            if s != "?" {
                s
            } else {
                c2s_name(op)
            }
        }
    }
}
